function deepMerge(target, source) {
  for (const [key, value] of Object.entries(source || {})) {
    if (value && typeof value === "object" && !Array.isArray(value)) {
      if (!target[key] || typeof target[key] !== "object" || Array.isArray(target[key])) target[key] = {};
      deepMerge(target[key], value);
    } else {
      target[key] = value;
    }
  }
  return target;
}

function cloneMessagePack(pack) {
  return JSON.parse(JSON.stringify(pack || {}));
}

function applyRuntimeMessages(messages) {
  if (!messages || typeof messages !== "object") return;
  if (messages["zh-CN"]) {
    messages["zh-CN"] = cloneMessagePack(messages["zh-CN"]);
    deepMerge(messages["zh-CN"], ZH_CN_RUNTIME_MESSAGES);
  }
  if (messages.en) {
    messages.en = cloneMessagePack(messages.en);
    deepMerge(messages.en, EN_RUNTIME_MESSAGES);
  }
  if (messages.ru) {
    messages.ru = cloneMessagePack(messages.ru);
    deepMerge(messages.ru, RU_RUNTIME_MESSAGES);
  }
}

function applyRussianRuntimeMessages(messages) {
  applyRuntimeMessages(messages);
}

